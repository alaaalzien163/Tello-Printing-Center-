-- ---------------------------------------------------------------------------
-- Private storage bucket and object policies
-- ---------------------------------------------------------------------------

insert into storage.buckets (id, name, public, file_size_limit)
values ('print-request-files', 'print-request-files', false, 52428800)
on conflict (id) do update
  set public = false,
      file_size_limit = excluded.file_size_limit;

-- Only administrators can list, read or delete customer attachments. Uploads
-- are authorized by server-minted signed upload tokens, which bypass these
-- policies without granting anonymous database or storage access. No INSERT
-- or UPDATE policy exists for anon/authenticated on purpose.
drop policy if exists "print_request_files_admin_read" on storage.objects;
create policy "print_request_files_admin_read"
  on storage.objects
  for select
  to authenticated
  using (
    bucket_id = 'print-request-files'
    and public.is_admin()
    and (storage.foldername(name))[1] = 'requests'
  );

drop policy if exists "print_request_files_admin_delete" on storage.objects;
create policy "print_request_files_admin_delete"
  on storage.objects
  for delete
  to authenticated
  using (
    bucket_id = 'print-request-files'
    and public.is_admin()
    and (storage.foldername(name))[1] = 'requests'
  );

