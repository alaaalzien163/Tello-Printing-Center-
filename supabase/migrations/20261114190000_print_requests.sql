-- Public print request intake, private attachments and admin-only access.
--
-- Apply this migration with the Supabase CLI (`supabase db push`) or by
-- pasting it into the SQL editor as a project owner. It is idempotent where
-- possible and never weakens the catalog or administrator policies.
--
-- Security model:
--   * Anonymous visitors never insert into these tables. The public API route
--     validates and rate-limits the submission, then writes with the
--     server-only secret key.
--   * Administrators read/update/delete request rows through RLS.
--   * Attachments live in the private `print-request-files` bucket. Only
--     administrators may list, read or delete objects. Customers upload with
--     short-lived signed upload tokens minted by the server.
--   * Raw IP addresses are never stored. The rate limiter receives an HMAC
--     hash generated in the application.

-- ---------------------------------------------------------------------------
-- Numeric request numbers
-- ---------------------------------------------------------------------------
--
-- The live project uses a bigint identity column starting at 1000. The
-- application renders it as a string but never relies on a text format.

-- ---------------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------------

create table if not exists public.print_requests (
  id uuid primary key default gen_random_uuid(),
  request_number bigint generated by default as identity (start with 1000) not null unique,
  client_token text,
  customer_name text not null,
  phone text not null,
  details text not null,
  locale text not null,
  status text not null default 'pending',
  is_read boolean not null default false,
  admin_notes text,
  client_hash text,
  file_count integer not null default 0,
  total_bytes bigint not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint print_requests_status_check check (
    status in (
      'uploading',
      'pending',
      'reviewing',
      'quoted',
      'approved',
      'completed',
      'rejected',
      'cancelled'
    )
  ),
  constraint print_requests_locale_check check (locale in ('en', 'ar')),
  constraint print_requests_name_length check (char_length(customer_name) between 2 and 120),
  constraint print_requests_phone_length check (char_length(phone) between 6 and 32),
  constraint print_requests_details_length check (char_length(details) between 5 and 10000),
  constraint print_requests_file_count_check check (file_count between 0 and 5),
  constraint print_requests_total_bytes_check check (total_bytes between 0 and 104857600),
  constraint print_requests_notes_length check (
    admin_notes is null or char_length(admin_notes) <= 5000
  )
);

